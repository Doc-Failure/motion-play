import { StrictMode } from 'react'
import { act, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { MagicDuel } from '../src/minigames/magic-duel/MagicDuel'
let frame: FrameRequestCallback
let now=0
function tick(time:number){now=time;act(()=>frame(time))}
const props={playerCount:2 as const,onExit:vi.fn()}
describe('Magic Duel rendered simulation',()=>{
  beforeEach(()=>{
    now=0;vi.spyOn(performance,'now').mockImplementation(()=>now)
    vi.stubGlobal('requestAnimationFrame',vi.fn((callback:FrameRequestCallback)=>{frame=callback;return 1}))
    vi.stubGlobal('cancelAnimationFrame',vi.fn())
    vi.stubGlobal('PointerEvent',MouseEvent)
  })
  afterEach(()=>{vi.restoreAllMocks();vi.unstubAllGlobals()})
  it.each([1,2,3,4] as const)('renders %i lanes with explicit simulation controls',playerCount=>{
    render(<MagicDuel {...props} playerCount={playerCount}/> )
    expect(screen.getAllByRole('group',{name:/Magic Duel play area/})).toHaveLength(playerCount)
    expect(screen.getByText(/Trace the dots/)).toBeVisible()
  })
  it('normalizes segmented pointer strokes in an isolated lane',()=>{
    render(<MagicDuel {...props}/>);tick(3100)
    const board=screen.getByRole('group',{name:'Player 2 Magic Duel play area'})
    vi.spyOn(board,'getBoundingClientRect').mockReturnValue({left:100,top:50,width:400,height:200} as DOMRect)
    fireEvent.pointerMove(board,{clientX:200,clientY:110});tick(3200)
    fireEvent.pointerMove(board,{clientX:250,clientY:150});tick(3300)
    fireEvent.pointerMove(board,{clientX:300,clientY:190});tick(3400)
    fireEvent.pointerMove(board,{clientX:400,clientY:110})
    expect(screen.getByText('20 points')).toBeVisible()
    fireEvent.pointerLeave(board);tick(3500)
    fireEvent.pointerMove(board,{clientX:200,clientY:110})
    expect(screen.getByText('20 points')).toBeVisible()
  })
  it('breaks pointer continuity on leave and rejects slow samples',()=>{
    render(<MagicDuel {...props}/>);tick(3100)
    const board=screen.getByRole('group',{name:'Player 1 Magic Duel play area'})
    vi.spyOn(board,'getBoundingClientRect').mockReturnValue({left:0,top:0,width:400,height:200} as DOMRect)
    fireEvent.pointerMove(board,{clientX:100,clientY:60});tick(3400)
    fireEvent.pointerMove(board,{clientX:200,clientY:140})
    expect(screen.getAllByText(/Valley · 0\/2 strokes/)[0]).toBeVisible()
    fireEvent.pointerLeave(board);tick(3500)
    fireEvent.pointerMove(board,{clientX:100,clientY:60})
    fireEvent.pointerLeave(board);tick(3600)
    fireEvent.pointerMove(board,{clientX:200,clientY:140});tick(3700)
    fireEvent.pointerMove(board,{clientX:300,clientY:60})
    expect(screen.getAllByText('0 points')).toHaveLength(2)
  })
  it('consumes generic swipes in StrictMode and focuses results/replay',()=>{
    const {rerender}=render(<StrictMode><MagicDuel {...props}/></StrictMode>);tick(3200)
    const events=[{playerId:1 as const,kind:'HAND_SWIPE' as const,x:.5,y:.7,confidence:1,timestamp:3200,swipe:{fromX:.25,fromY:.3,durationMs:100}}]
    rerender(<StrictMode><MagicDuel {...props} inputEvents={events}/></StrictMode>)
    tick(3400)
    fireEvent.keyDown(screen.getByRole('group',{name:'Player 1 Magic Duel play area'}),{key:'Enter'})
    expect(screen.getByText('20 points')).toBeVisible()
    rerender(<StrictMode><MagicDuel {...props} inputEvents={[...events]}/></StrictMode>)
    expect(screen.getByText('20 points')).toBeVisible()
    tick(63000)
    expect(screen.getByRole('dialog',{name:'Magic Duel results'})).toHaveTextContent('Player 1: 20 points')
    expect(screen.getByRole('heading',{name:'Wonderful spells!'})).toHaveFocus()
    fireEvent.click(screen.getByRole('button',{name:'Play again'}))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.getByRole('group',{name:'Player 1 Magic Duel play area'})).toHaveFocus()
    expect(screen.getAllByText('0 points')).toHaveLength(2)
  })
  it('supports per-edge keyboard simulation without repeats',()=>{
    render(<MagicDuel {...props}/>);tick(3200)
    const board=screen.getByRole('group',{name:'Player 1 Magic Duel play area'})
    fireEvent.keyDown(board,{key:'Enter',repeat:true})
    expect(screen.getAllByText('0 points')).toHaveLength(2)
    fireEvent.keyDown(board,{key:'Enter'});tick(3400)
    expect(screen.getAllByText('0 points')).toHaveLength(2)
    fireEvent.keyDown(board,{key:'Enter'})
    expect(screen.getByText('20 points')).toBeVisible()
    expect(screen.getByText('0 points')).toBeVisible()
  })
  it('preserves manual/camera/tab recovery and exit',()=>{
    const reconnect=vi.fn();const {rerender}=render(<MagicDuel {...props} onReconnect={reconnect}/>);tick(4000)
    fireEvent.click(screen.getByRole('button',{name:'Pause'}));tick(14000)
    expect(screen.getByText('59s')).toBeVisible()
    fireEvent.click(screen.getByRole('button',{name:'Resume round'}))
    expect(screen.getByRole('button',{name:'Pause'})).toHaveFocus()
    rerender(<MagicDuel {...props} externalPauseReason="Camera disconnected" onReconnect={reconnect}/>)
    expect(screen.getByRole('button',{name:'Resume round'})).toBeDisabled()
    fireEvent.click(screen.getByRole('button',{name:'Reconnect camera'}));expect(reconnect).toHaveBeenCalledOnce()
    rerender(<MagicDuel {...props}/>);fireEvent.click(screen.getByRole('button',{name:'Resume round'}))
    vi.spyOn(document,'hidden','get').mockReturnValue(true);fireEvent(document,new Event('visibilitychange'))
    expect(screen.getByRole('dialog')).toHaveTextContent('The tab was hidden')
    fireEvent.click(screen.getByRole('button',{name:'Return to setup'}));expect(props.onExit).toHaveBeenCalled()
  })
})
