import {completeReadyGate,expect,openApp,test} from './fixtures'
test('fullscreen works across menus and gameplay and keeps the same camera',async({page,installMockCamera})=>{
 await installMockCamera({person:true})
 await openApp(page,'#/',async()=>{await page.route('**/pose/tracker.js',r=>r.fulfill({contentType:'text/javascript',body:'window.createLocalPoseTracker=async()=>({detect:()=>[],close:()=>{}})'}))})
 await page.getByRole('button',{name:'Enter fullscreen',exact:true}).click()
 await expect.poll(()=>page.evaluate(()=>document.fullscreenElement===document.documentElement)).toBe(true)
 await page.getByRole('button',{name:'1 player',exact:true}).click()
 await page.getByRole('link',{name:/Game Catalog/}).click()
 await expect(page.getByRole('button',{name:'Exit fullscreen',exact:true})).toBeVisible()
 await page.getByRole('link',{name:'Play UFO Juggler',exact:true}).click();await completeReadyGate(page)
 await expect(page.locator('.ufo-game')).toHaveAttribute('data-phase','playing',{timeout:5000})
 const full=await page.getByRole('button',{name:'Exit fullscreen',exact:true}).boundingBox(),sound=await page.getByRole('button',{name:'Mute game sound'}).boundingBox()
 expect(sound!.x+sound!.width).toBeLessThan(full!.x)
 await page.screenshot({path:test.info().outputPath('fullscreen-game.png')})
 await page.getByRole('button',{name:'Exit fullscreen',exact:true}).click()
 await expect.poll(()=>page.evaluate(()=>document.fullscreenElement)).toBeNull()
 await page.getByRole('button',{name:'Enter fullscreen',exact:true}).focus();await page.keyboard.press('Enter')
 await expect.poll(()=>page.evaluate(()=>Boolean(document.fullscreenElement))).toBe(true)
 await page.evaluate(()=>document.exitFullscreen())
 await expect(page.getByRole('button',{name:'Enter fullscreen',exact:true})).toHaveAttribute('aria-pressed','false')
 expect(await page.evaluate(()=>(window as typeof window&{__mockMediaState:{requests:number;stoppedTracks:number}}).__mockMediaState)).toMatchObject({requests:1,stoppedTracks:0})
})
