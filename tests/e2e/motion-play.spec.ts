test('renders separate two-player layouts and scores a deterministic pointer hit', async ({ page }) => {
  await openCamera(page)
  await page.getByRole('button', { name: '2 players' }).click()
  const layout = page.getByLabel('2 player game viewport layout')
  await expect(layout.locator('div')).toHaveCount(2)
  await page.getByRole('button', { name: 'Use demo mode' }).click()
  await page.getByRole('button', { name: 'Play Bubble Battle' }).click()
  await expect(page.getByRole('heading', { name: 'Wave at the bubbles' })).toBeVisible()
  await page.getByRole('button', { name: 'Start round now' }).click()
  await expect(page.getByLabel('Player 1 Bubble Battle play area')).toBeVisible()
  await expect(page.getByLabel('Player 2 Bubble Battle play area')).toBeVisible()
  await expect(page.locator('.game-curtain').first()).toContainText('3')
  await expect(page.locator('.game-curtain')).toHaveCount(0, { timeout: 5_000 })
  await page.getByRole('button', { name: 'Pause' }).click()
  await expect(page.getByRole('dialog', { name: 'Hold that pose!' })).toBeVisible()
  await page.getByRole('button', { name: 'Resume round' }).click()
  await expect(page.getByRole('dialog', { name: 'Hold that pose!' })).toHaveCount(0)
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: true }); document.dispatchEvent(new Event('visibilitychange')) })
  await expect(page.getByRole('dialog', { name: 'Hold that pose!' })).toContainText('tab was hidden')
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: false }); document.dispatchEvent(new Event('visibilitychange')) })
  await page.getByRole('button', { name: 'Resume round' }).click()

  const playerOneBoard = page.getByLabel('Player 1 Bubble Battle play area')
  const target = playerOneBoard.locator('.battle-target--bubble').first()
  await expect(target).toBeVisible()
  await expect.poll(async () => {
    const [targetBox, boardBox] = await Promise.all([target.boundingBox(), playerOneBoard.boundingBox()])
    if (!targetBox || !boardBox) return false
    const centerY = targetBox.y + targetBox.height / 2
    return centerY > boardBox.y && centerY < boardBox.y + boardBox.height
  }, { timeout: 5_000 }).toBe(true)
  const targetBox = await target.boundingBox()
  expect(targetBox).not.toBeNull()
  await page.mouse.click(targetBox!.x + targetBox!.width / 2, targetBox!.y + targetBox!.height / 2)
  await expect(page.locator('.bubble-game__header dl > div').filter({ hasText: 'Player 1' }).locator('dd')).toHaveText('10')
  await expect(page.locator('.bubble-game__header dl > div').filter({ hasText: 'Player 2' }).locator('dd')).toHaveText('0')
})
