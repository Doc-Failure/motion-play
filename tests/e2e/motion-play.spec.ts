test('permission failure offers a clear retry without settings',async ({page,installMockCamera}) => {
  await installMockCamera({denied:true})
  await openApp(page)
  await expect(page.getByRole('alert')).toContainText('Camera permission is blocked')
  await expect(page.getByRole('button',{name:'Activate camera & play'})).toBeEnabled()
  await expect(page.getByRole('slider')).toHaveCount(0)
})

test('Piñata Party supports four players, keyboard and pointer hits, and pause', async ({ page, installMockCamera }) => {
  await page.clock.install()
  await installMockCamera()
  await openApp(page, '#/catalog')
  await page.getByRole('link', { name: 'Play Piñata Party' }).click()
  await page.getByRole('button', { name: '4 players' }).click()
  await page.getByRole('button', { name: 'Play Piñata Party' }).click()
  await expect(page.getByRole('heading', { name: 'Fill the candy jar together' })).toBeVisible()
  await page.getByRole('button', { name: 'Start round now' }).click()
  const target = page.getByRole('button', { name: 'Hit Player 1 piñata' })
  await page.clock.runFor(3100)
  for (const playerId of [1, 2, 3, 4]) {
    await expect(page.getByLabel(`Player ${playerId} Piñata Party play area`)).toBeVisible()
  }
  await target.focus()
  await page.keyboard.press('Enter')
  await page.clock.runFor(350)
  await page.keyboard.press('Space')
  await page.clock.runFor(350)
  await target.click()
  await expect(page.getByText('+10 candy!')).toBeVisible()
  await expect(page.getByRole('region', { name: 'Player 1', exact: true })).toContainText('10 candy')
  await expect(page.getByRole('region', { name: 'Player 2', exact: true })).toContainText('0 candy')
  await expect(page.getByText('10 / 200', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/pinata-party-four-players.png', fullPage: true })
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Piñata Party paused' })).toBeVisible()
  await page.clock.runFor(5000)
  await page.getByRole('button', { name: 'Resume' }).click()
  await page.clock.runFor(900)
  await expect(target).toBeEnabled()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/pinata-party-narrow.png', fullPage: true })
  await page.getByRole('button', { name: 'Exit game' }).click()
  await expect(page.getByRole('button', { name: 'Play Piñata Party' })).toBeEnabled()
})
