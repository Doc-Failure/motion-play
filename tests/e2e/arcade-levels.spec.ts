import {test,expect,openApp,completeReadyGate} from './fixtures'
test('miss the Dojo goal, replay from results and return to the catalog',async({page,installMockCamera})=>{
 test.setTimeout(60000)
 await page.addInitScript(()=>Object.assign(window,{__testClockInstalled:true}))
 await page.clock.install({time:new Date('2030-01-01T00:00:00Z')})
 await page.clock.pauseAt(new Date('2030-01-01T00:01:00Z'))
 await installMockCamera({person:true})
 await openApp(page,'?soloAssist=1#/camera/ninja-training',async()=>{
  await page.route('**/pose/tracker.js',r=>r.fulfill({contentType:'text/javascript',body:'window.createLocalPoseTracker=async()=>({detect:()=>[],close:()=>{}})'}))
 })
 await page.getByRole('button',{name:'1 player',exact:true}).click()
 await completeReadyGate(page)
 await page.clock.runFor(3100)
 await page.clock.fastForward(45000)
 const dialog=page.getByRole('dialog',{name:'Paper Dojo results'})
 await expect(dialog).toBeVisible()
 await expect(dialog.getByText(/P1 best/)).toHaveCount(0)
 await expect(dialog.getByRole('checkbox')).toHaveCount(0)
 await expect(dialog.getByRole('button',{name:'Quick retry'})).toHaveCount(0)
 await dialog.getByRole('button',{name:'Play again'}).click()
 await completeReadyGate(page)
 await page.clock.runFor(3100)
 await expect(page.locator('.dojo-game header dd').first()).toHaveText('0')
 await page.clock.fastForward(45000)
 await dialog.getByRole('button',{name:'Back to games'}).click()
 await expect(page.getByRole('heading',{name:'Game Catalog',exact:true})).toBeVisible()
 expect(await page.evaluate(()=>(window as typeof window&{__mockMediaState:{requests:number}}).__mockMediaState.requests)).toBe(1)
})
